// @vitest-environment jsdom

import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import {
  POINTER_SNAPSHOT_CROP,
  POINTER_SNAPSHOT_LENS_SIZE,
  parseComputerPointerSnapshotMessage,
} from "./computer-pointer-snapshot";

/**
 * The screen page the capture script runs against: a #screen div holding the
 * noVNC canvas (the canvas RFB builds; its backing store is the framebuffer,
 * so canvas pixels are desktop pixels 1:1). jsdom has no 2D context, so the
 * context and toDataURL are stubbed — the test proves the script's crop math
 * and message shape, not the browser's rasteriser.
 */
type DrawCall = Array<number | HTMLCanvasElement>;

function stubCanvasApis() {
  const draws: DrawCall[] = [];
  const fills: Array<{ x: number; y: number; w: number; h: number }> = [];
  const context = {
    fillStyle: "",
    fillRect(x: number, y: number, w: number, h: number) {
      fills.push({ x, y, w, h });
    },
    drawImage(
      canvas: HTMLCanvasElement,
      sx: number,
      sy: number,
      sw: number,
      sh: number,
      dx: number,
      dy: number,
      dw: number,
      dh: number,
    ) {
      draws.push([canvas, sx, sy, sw, sh, dx, dy, dw, dh]);
    },
  };
  vi.spyOn(HTMLCanvasElement.prototype, "getContext").mockImplementation(
    () => context as unknown as CanvasRenderingContext2D,
  );
  vi.spyOn(HTMLCanvasElement.prototype, "toDataURL").mockImplementation(
    () => "data:image/jpeg;base64,fakelens",
  );
  return { draws, fills };
}

describe("computerPointerSnapshotScript", () => {
  let postMessage: ReturnType<typeof vi.fn>;

  beforeEach(() => {
    postMessage = vi.fn();
    (window as unknown as { ReactNativeWebView: { postMessage: unknown } }).ReactNativeWebView = {
      postMessage,
    };
  });

  afterEach(() => {
    document.body.innerHTML = "";
    vi.restoreAllMocks();
    vi.useRealTimers();
  });

  async function runScript(pointer: { x: number; y: number; seq: number }) {
    const { computerPointerSnapshotScript } = await import("./computer-pointer-snapshot");
    const script = computerPointerSnapshotScript(pointer);
    expect(script.trimEnd().endsWith("true;})();")).toBe(true);
    // A <script> element does not execute under vitest's jsdom, so the
    // generated injection runs through eval here. Test-only: the script is
    // generated by the module under test from fixed numbers, no user input
    // reaches it.
    // biome-ignore lint/security/noGlobalEval: test-only, see above.
    window.eval(script);
  }

  function screenCanvas(width: number, height: number): HTMLCanvasElement {
    const screen = document.createElement("div");
    screen.id = "screen";
    const canvas = document.createElement("canvas");
    canvas.width = width;
    canvas.height = height;
    screen.appendChild(canvas);
    document.body.appendChild(screen);
    return canvas;
  }

  it("posts a JPEG data URL for the region around the click", async () => {
    const { draws } = stubCanvasApis();
    const canvas = screenCanvas(1280, 720);
    await runScript({ x: 640, y: 360, seq: 7 });
    expect(postMessage).toHaveBeenCalledTimes(1);
    const payload = JSON.parse(String(postMessage.mock.calls[0]![0]));
    expect(payload).toEqual({
      type: "rakazo-pointer-snapshot",
      seq: 7,
      dataUrl: "data:image/jpeg;base64,fakelens",
    });
    // A 56px crop centred on (640, 360), scaled 2.5x into a 140px lens.
    expect(draws).toHaveLength(1);
    expect(draws[0]![0]).toBe(canvas);
    expect(draws[0]!.slice(1)).toEqual([
      640 - POINTER_SNAPSHOT_CROP / 2,
      360 - POINTER_SNAPSHOT_CROP / 2,
      POINTER_SNAPSHOT_CROP,
      POINTER_SNAPSHOT_CROP,
      0,
      0,
      POINTER_SNAPSHOT_LENS_SIZE,
      POINTER_SNAPSHOT_LENS_SIZE,
    ]);
  });

  it("keeps the click at the centre when it is near the edge", async () => {
    const { draws } = stubCanvasApis();
    screenCanvas(1280, 720);
    await runScript({ x: 10, y: 10, seq: 8 });
    expect(postMessage).toHaveBeenCalledTimes(1);
    // Ideal crop starts at (-18, -18); clamped to (0, 0, 38, 38) and drawn
    // 45px in (18 * 2.5), so the click stays at the lens centre.
    expect(draws).toHaveLength(1);
    expect(draws[0]!.slice(1)).toEqual([0, 0, 38, 38, 45, 45, 95, 95]);
  });

  it("finds the stock noVNC canvas when there is no #screen canvas", async () => {
    const { draws } = stubCanvasApis();
    const canvas = document.createElement("canvas");
    canvas.id = "noVNC_canvas";
    canvas.width = 800;
    canvas.height = 600;
    document.body.appendChild(canvas);
    await runScript({ x: 400, y: 300, seq: 9 });
    expect(postMessage).toHaveBeenCalledTimes(1);
    expect(draws[0]![0]).toBe(canvas);
  });

  it("retries once, then reports no-canvas when the page has no canvas", async () => {
    vi.useFakeTimers();
    stubCanvasApis();
    await runScript({ x: 100, y: 100, seq: 10 });
    expect(postMessage).not.toHaveBeenCalled();
    await vi.advanceTimersByTimeAsync(900);
    expect(postMessage).toHaveBeenCalledTimes(1);
    expect(JSON.parse(String(postMessage.mock.calls[0]![0]))).toEqual({
      type: "rakazo-pointer-snapshot",
      seq: 10,
      error: "no-canvas",
    });
  });

  it("reports no-canvas at once when the canvas is still 0-sized after the retry", async () => {
    vi.useFakeTimers();
    stubCanvasApis();
    const canvas = screenCanvas(0, 0);
    await runScript({ x: 100, y: 100, seq: 11 });
    // A 0-sized canvas is not a frame yet; the retry finds it still empty.
    expect(postMessage).not.toHaveBeenCalled();
    canvas.width = 1280;
    canvas.height = 720;
    await vi.advanceTimersByTimeAsync(900);
    expect(postMessage).toHaveBeenCalledTimes(1);
    expect(JSON.parse(String(postMessage.mock.calls[0]![0])).dataUrl).toBe(
      "data:image/jpeg;base64,fakelens",
    );
  });
});

describe("parseComputerPointerSnapshotMessage", () => {
  it("accepts a snapshot message", () => {
    expect(
      parseComputerPointerSnapshotMessage(
        JSON.stringify({
          type: "rakazo-pointer-snapshot",
          seq: 3,
          dataUrl: "data:image/jpeg;base64,abc",
        }),
      ),
    ).toEqual({ seq: 3, dataUrl: "data:image/jpeg;base64,abc" });
  });

  it("accepts a failure message", () => {
    expect(
      parseComputerPointerSnapshotMessage(
        JSON.stringify({ type: "rakazo-pointer-snapshot", seq: 3, error: "no-canvas" }),
      ),
    ).toEqual({ seq: 3, error: "no-canvas" });
  });

  it.each([
    ["not JSON", "hello"],
    ["another message type", JSON.stringify({ type: "screen-state", state: "ready" })],
    [
      "a non-image data URL",
      JSON.stringify({ type: "rakazo-pointer-snapshot", seq: 3, dataUrl: "data:text/plain,hi" }),
    ],
    ["no seq", JSON.stringify({ type: "rakazo-pointer-snapshot", dataUrl: "data:image/png,x" })],
    ["neither data nor error", JSON.stringify({ type: "rakazo-pointer-snapshot", seq: 3 })],
  ])("returns null: %s", (_label, data) => {
    expect(parseComputerPointerSnapshotMessage(data)).toBeNull();
  });
});

describe("handleComputerPointerSnapshotMessage", () => {
  it("stores a snapshot on the matching pointer and ignores anything else", async () => {
    vi.resetModules();
    const pointerMod = await import("./computer-pointer");
    const snapshotMod = await import("./computer-pointer-snapshot");
    pointerMod.setComputerPointer({ botId: "bot-1", x: 640, y: 360, width: 1280, height: 720 });
    const seq = pointerMod.computerPointer()?.seq;
    expect(seq).toBeTypeOf("number");
    expect(
      snapshotMod.handleComputerPointerSnapshotMessage(
        JSON.stringify({ type: "rakazo-pointer-snapshot", seq, dataUrl: "data:image/jpeg,x" }),
      ),
    ).toBe(true);
    expect(pointerMod.computerPointer()?.snapshot).toBe("data:image/jpeg,x");
    // A failed capture is still a snapshot message (handled), but stores nothing.
    expect(
      snapshotMod.handleComputerPointerSnapshotMessage(
        JSON.stringify({ type: "rakazo-pointer-snapshot", seq, error: "no-canvas" }),
      ),
    ).toBe(true);
    expect(pointerMod.computerPointer()?.snapshot).toBe("data:image/jpeg,x");
    // Anything else falls through to the caller's own handling.
    expect(
      snapshotMod.handleComputerPointerSnapshotMessage(JSON.stringify({ type: "ready" })),
    ).toBe(false);
    expect(snapshotMod.handleComputerPointerSnapshotMessage("not json")).toBe(false);
  });
});

describe("useComputerPointerSnapshot", () => {
  it("injects the capture script for a new pointer and retries once when empty", async () => {
    vi.resetModules();
    vi.useFakeTimers();
    const pointerMod = await import("./computer-pointer");
    const snapshotMod = await import("./computer-pointer-snapshot");
    const { createElement } = await import("react");
    const { act } = await import("react");
    const { createRoot } = await import("react-dom/client");
    const injectJavaScript = vi.fn();
    const ref = { current: { injectJavaScript } };
    const container = document.createElement("div");
    document.body.appendChild(container);
    const root = createRoot(container);
    function Probe() {
      snapshotMod.useComputerPointerSnapshot(
        ref as unknown as Parameters<typeof snapshotMod.useComputerPointerSnapshot>[0],
      );
      return null;
    }
    await act(async () => {
      root.render(createElement(Probe));
    });
    pointerMod.setComputerPointer({ botId: "bot-1", x: 100, y: 200, width: 1280, height: 720 });
    await act(async () => {});
    expect(injectJavaScript).toHaveBeenCalledTimes(1);
    expect(String(injectJavaScript.mock.calls[0]![0])).toContain("rakazo-pointer-snapshot");
    // No snapshot came back: one retry after 2s, then no more.
    await act(async () => {
      vi.advanceTimersByTime(2000);
    });
    expect(injectJavaScript).toHaveBeenCalledTimes(2);
    await act(async () => {
      vi.advanceTimersByTime(5000);
    });
    expect(injectJavaScript).toHaveBeenCalledTimes(2);
    // A new pointer starts the cycle again.
    pointerMod.setComputerPointer({ botId: "bot-1", x: 300, y: 400, width: 1280, height: 720 });
    await act(async () => {});
    expect(injectJavaScript).toHaveBeenCalledTimes(3);
    await act(async () => {
      root.unmount();
    });
    container.remove();
    vi.useRealTimers();
  });

  it("does not inject when the pointer already has a snapshot", async () => {
    vi.resetModules();
    const pointerMod = await import("./computer-pointer");
    const snapshotMod = await import("./computer-pointer-snapshot");
    const { createElement } = await import("react");
    const { act } = await import("react");
    const { createRoot } = await import("react-dom/client");
    const injectJavaScript = vi.fn();
    const ref = { current: { injectJavaScript } };
    const container = document.createElement("div");
    document.body.appendChild(container);
    const root = createRoot(container);
    function Probe() {
      snapshotMod.useComputerPointerSnapshot(
        ref as unknown as Parameters<typeof snapshotMod.useComputerPointerSnapshot>[0],
      );
      return null;
    }
    pointerMod.setComputerPointer({ botId: "bot-1", x: 100, y: 200, width: 1280, height: 720 });
    const seq = pointerMod.computerPointer()?.seq;
    pointerMod.setComputerPointerSnapshot(seq ?? -1, "data:image/jpeg,x");
    await act(async () => {
      root.render(createElement(Probe));
    });
    await act(async () => {});
    expect(injectJavaScript).not.toHaveBeenCalled();
    await act(async () => {
      root.unmount();
    });
    container.remove();
  });
});
